// src/_data/site.js  ->  available in every template as {{ site.* }}
// Pulls Platform Name / Description / Default Social Sharing Image from the
// "Site Settings" document in Sanity. Anything missing falls back to the defaults below,
// so the build never breaks if the document is empty or Sanity is unreachable.
//
// Uses the shared Sanity client (sanityClient.js), so project ID, dataset and
// API version are defined in ONE place and always match the other data files.

const client = require("./sanityClient");

const SITE_URL = process.env.SITE_URL || "https://www.yourdomain.com"; // no trailing slash. CHANGE THIS
const TWITTER = ""; // e.g. "@edunews" (optional)

// Published document only (ignore drafts). If there are ever two, the most recently edited wins.
// The image is cropped to 1200x630 by Sanity's CDN.
const QUERY = `*[_type == "siteSettings" && !(_id in path("drafts.**"))] | order(_updatedAt desc)[0]{
  title_ar,
  title_en,
  description_ar,
  description_en,
  siteUrl,
  themeColor,
  twitterHandle,
  facebookUrl, xUrl, instagramUrl, youtubeUrl, linkedinUrl, tiktokUrl,
  "logo": logo.asset->url,
  "favicon": favicon.asset->url,
  "ogImage": defaultOgImage.asset->url
}`;

module.exports = async function () {
  let s = {};
  try {
    s = (await client.fetch(QUERY)) || {};
  } catch (err) {
    console.warn("[site.js] Could not load siteSettings from Sanity, using defaults:", err.message);
  }

  const ogImage = s.ogImage
    ? `${s.ogImage}?w=1200&h=630&fit=crop&auto=format`
    : "/assets/img/og-default.jpg"; // fallback file in your project (1200x630)

  const handle = s.twitterHandle ? "@" + s.twitterHandle.replace(/^@/, "").trim() : TWITTER;
  const sameAs = [s.facebookUrl, s.xUrl, s.instagramUrl, s.youtubeUrl, s.linkedinUrl, s.tiktokUrl].filter(Boolean);

  return {
    url: (s.siteUrl || SITE_URL).replace(/\/+$/, ""),
    twitter: handle,
    themeColor: s.themeColor || "",
    sameAs,
    social: {
      facebook: s.facebookUrl, x: s.xUrl, instagram: s.instagramUrl,
      youtube: s.youtubeUrl, linkedin: s.linkedinUrl, tiktok: s.tiktokUrl,
    },

    defaultImage: ogImage,
    // Logo: raw Sanity URL (works for SVG/PNG). Add ?h=80 in a template to resize rasters.
    logo: s.logo || "",
    // Favicon sizes generated by Sanity's CDN. Empty when no favicon is uploaded.
    favicon32: s.favicon ? `${s.favicon}?w=32&h=32&fit=crop&fm=png` : "",
    favicon192: s.favicon ? `${s.favicon}?w=192&h=192&fit=crop&fm=png` : "",
    appleTouchIcon: s.favicon ? `${s.favicon}?w=180&h=180&fit=crop&fm=png` : "",

    ar: {
      locale: "ar_AR",
      name: s.title_ar || "EduNews",
      defaultTitle: s.title_ar || "EduNews | أخبار التعليم",
      description: s.description_ar || "آخر أخبار التعليم والسياسات التعليمية والاستثمار في قطاع التعليم.",
    },
    en: {
      locale: "en_US",
      name: s.title_en || "EduNews",
      defaultTitle: s.title_en || "EduNews | Education News",
      description: s.description_en || "Latest education news, policy analysis and investment coverage.",
    },
  };
};